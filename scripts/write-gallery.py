#!/usr/bin/env python3
"""Write docs/gallery/README.md listing the screenshots in order, with a caption for each."""
import pathlib
import sys

CAPTIONS = {
    "01-try-it": "Try it: the app, with sample text",
    "02-sheet-opens-translating": "Translate opens the sheet and runs at once",
    "03-sheet-language-switched": "Tap a language chip: it runs again in that language",
    "04-sheet-action-switched": "Tap an action chip: Polish, from the same text",
    "05-sheet-quick-prompt-typed": "Quick prompt: type what you want changed",
    "06-sheet-quick-prompt-result": "The quick prompt's result, streamed in",
    "07-replaced-in-text": "Replace writes the result back into the text field",
    "08-tab-actions": "Actions: choose which chips show, and their order",
    "09-tab-languages": "Languages: your two main languages and the chips",
    "10-tab-engine": "Engine: Claude, an OpenAI-compatible server, on-device, or demo",
    "11-tab-set-up": "Set up: make OhMyTranslate the default Translate",
}

out = pathlib.Path(sys.argv[1])
images = sorted(p.name for p in out.glob("*.png"))
lines = [
    "# App gallery",
    "",
    "Screenshots from the UI tour in `OhMyTranslateUITests`, regenerated by CI on each push to `dev/*`.",
    "Simulator: iPhone 17 Pro, iOS 26.2.",
    "",
]
for name in images:
    stem = name[:-4]
    lines += [f"### {CAPTIONS.get(stem, stem)}", "", f"![{stem}]({name})", ""]
(out / "README.md").write_text("\n".join(lines))
print(f"{len(images)} screenshots")
