#!/usr/bin/env python3
"""Write docs/gallery/README.md and refresh the gallery table in the top-level README.

Usage: write-gallery.py docs/gallery README.md
The README table sits between <!-- gallery:start --> and <!-- gallery:end -->; it is rebuilt from
the PNGs in the gallery folder, four per row, so the README always matches the screenshots.
"""
import pathlib
import re
import sys

CAPTIONS = {
    "01-try-it": "Try it: the app with sample text",
    "02-sheet-opens-auto-detected": "Translate opens the sheet, language detected",
    "03-sheet-source-menu": "Source language: detect, or pick one",
    "04-sheet-language-switched": "Tap a language: it runs again",
    "05-sheet-action-switched": "Tap an action: Polish, same text",
    "06-sheet-quick-prompt-typed": "Quick prompt: say what to change",
    "07-sheet-quick-prompt-result": "The quick prompt's result, streamed",
    "08-replaced-in-text": "Replace writes it back into the text",
    "09-tab-actions": "Actions: which chips show, and their order",
    "10-tab-settings": "Settings: languages and the default search",
    "11-tab-engine": "Engine: Claude, OpenAI-compatible, on-device or demo",
    "12-tab-set-up": "Set up: make it the default Translate",
}

gallery_dir = pathlib.Path(sys.argv[1])
readme = pathlib.Path(sys.argv[2])
images = sorted(p.name for p in gallery_dir.glob("*.png"))

index = [
    "# App gallery",
    "",
    "Screenshots from the UI tour in `OhMyTranslateUITests`, regenerated by CI on each push to `dev/*`.",
    "Simulator: iPhone 17 Pro, iOS 26.2.",
    "",
]
for name in images:
    stem = name[:-4]
    index += [f"### {CAPTIONS.get(stem, stem)}", "", f"![{stem}]({name})", ""]
(gallery_dir / "README.md").write_text("\n".join(index))

cells = [(f'<img src="docs/gallery/{n}" width="200" alt="{CAPTIONS.get(n[:-4], n[:-4])}">',
          f"**{CAPTIONS.get(n[:-4], n[:-4])}**") for n in images]
rows = []
for i in range(0, len(cells), 4):
    chunk = cells[i:i + 4]
    rows.append("| " + " | ".join(c[0] for c in chunk) + " |" + " |" * (4 - len(chunk)))
    rows.append("| " + " | ".join(c[1] for c in chunk) + " |" + " |" * (4 - len(chunk)))
    if i == 0:
        rows[0:0] = ["|   |   |   |   |", "|:-:|:-:|:-:|:-:|"]
table = "\n".join(rows)

text = readme.read_text()
block = f"<!-- gallery:start -->\n{table}\n<!-- gallery:end -->"
if "<!-- gallery:start -->" in text:
    text = re.sub(r"<!-- gallery:start -->.*?<!-- gallery:end -->", lambda _: block, text, flags=re.S)
    readme.write_text(text)
print(f"{len(images)} screenshots")
